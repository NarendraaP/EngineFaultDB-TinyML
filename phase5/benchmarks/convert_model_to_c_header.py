#!/usr/bin/env python3
"""
Phase 5.1 — TFLite Model to C Header Converter
================================================
Converts binary .tflite model files into C byte arrays (`const unsigned char[]`)
suitable for embedding into microcontroller flash memory via TFLite Micro.
"""

import os, sys

def convert_tflite_to_c_header(tflite_path, header_path, variable_name):
    if not os.path.exists(tflite_path):
        raise FileNotFoundError(f"Model file not found: {tflite_path}")

    with open(tflite_path, "rb") as f:
        data = f.read()

    size_bytes = len(data)

    os.makedirs(os.path.dirname(header_path), exist_ok=True)

    with open(header_path, "w") as f:
        f.write("/* Automatically generated by Phase 5.1 Model Converter */\n")
        f.write(f"#ifndef {variable_name.upper()}_H_\n")
        f.write(f"#define {variable_name.upper()}_H_\n\n")
        f.write('#include <cstdint>\n\n')
        f.write(f"alignas(16) const unsigned char {variable_name}[] = {{\n")

        for i, b in enumerate(data):
            f.write(f"0x{b:02x}, ")
            if (i + 1) % 12 == 0:
                f.write("\n  ")

        f.write("\n};\n\n")
        f.write(f"const unsigned int {variable_name}_len = {size_bytes};\n\n")
        f.write(f"#endif // {variable_name.upper()}_H_\n")

    print(f"Converted {tflite_path} ({size_bytes} B) -> {header_path}")

if __name__ == "__main__":
    base_dir = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    models_dir = os.path.join(base_dir, "phase5", "models")
    firmware_inc_dir = os.path.join(base_dir, "phase5", "firmware", "include")

    models_to_convert = [
        ("student_b_16_4_int8.tflite", "g_student_b_model_data"),
        ("student_a_8_4_int8.tflite", "g_student_a_model_data"),
        ("mlp_12f_int8.tflite", "g_mlp_12f_model_data"),
        ("mlp_14f_int8.tflite", "g_mlp_14f_model_data"),
    ]

    for model_file, var_name in models_to_convert:
        src = os.path.join(models_dir, model_file)
        dst = os.path.join(firmware_inc_dir, f"{var_name}.h")
        convert_tflite_to_c_header(src, dst, var_name)
