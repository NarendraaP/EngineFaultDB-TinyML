#!/usr/bin/env python3
"""
Phase 5.1 — MCU Test Vector Generator
======================================
Reads EngineFaultDB_Final.csv, applies Phase 2 scaler.pkl normalization,
quantizes to INT8 using authoritative TFLite input quantization parameters,
and generates C header files containing test vectors and expected outputs.
"""

import os, sys
import numpy as np
import pandas as pd
import joblib
import tensorflow as tf

RANDOM_SEED = 42

BASE_DIR  = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CSV_PATH  = os.path.join(BASE_DIR, "EngineFaultDB_Final.csv")
MODEL_DIR = os.path.join(BASE_DIR, "models")
SCALER_PATH = os.path.join(MODEL_DIR, "scaler.pkl")
DST_HEADER  = os.path.join(BASE_DIR, "phase5", "firmware", "include", "mcu_test_vectors.h")

def generate_test_vectors():
    df = pd.read_csv(CSV_PATH).drop_duplicates()
    TARGET = "Fault"
    ALL_FEATURES = [c for c in df.columns if c != TARGET]
    
    X = df[ALL_FEATURES].values
    y = df[TARGET].values
    
    scaler = joblib.load(SCALER_PATH)
    X_norm = scaler.transform(X)
    
    # Load Primary Candidate TFLite model to get exact quantization parameters
    tflite_path = os.path.join(BASE_DIR, "phase5", "models", "student_b_16_4_int8.tflite")
    interpreter = tf.lite.Interpreter(model_path=tflite_path)
    interpreter.allocate_tensors()
    
    input_details = interpreter.get_input_details()
    scale, zero_point = input_details[0]['quantization']
    print(f"Loaded student_b_16_4_int8.tflite quant params: Scale={scale}, ZeroPoint={zero_point}")
    
    # Select 20 representative test vectors (5 per class)
    samples = []
    labels = []
    
    for cls in range(4):
        cls_indices = np.where(y == cls)[0]
        selected_idx = cls_indices[:5]
        for idx in selected_idx:
            samples.append(X_norm[idx])
            labels.append(y[idx])
            
    samples = np.array(samples)
    labels = np.array(labels)
    
    # Quantize samples to int8
    samples_q = np.round(samples / scale + zero_point).clip(-128, 127).astype(np.int8)
    
    os.makedirs(os.path.dirname(DST_HEADER), exist_ok=True)
    with open(DST_HEADER, "w") as f:
        f.write("/* Automatically generated by Phase 5.1 Test Vector Generator */\n")
        f.write("#ifndef MCU_TEST_VECTORS_H_\n")
        f.write("#define MCU_TEST_VECTORS_H_\n\n")
        f.write('#include <cstdint>\n\n')
        f.write(f"const float QUANT_SCALE = {scale}f;\n")
        f.write(f"const int32_t QUANT_ZERO_POINT = {zero_point};\n")
        f.write(f"const int NUM_TEST_SAMPLES = {len(samples)};\n")
        f.write(f"const int FEATURE_DIM = {len(ALL_FEATURES)};\n\n")
        
        f.write("const int8_t TEST_SAMPLES_INT8[NUM_TEST_SAMPLES][FEATURE_DIM] = {\n")
        for s in samples_q:
            f.write("  { " + ", ".join(map(str, s)) + " },\n")
        f.write("};\n\n")
        
        f.write("const uint8_t TEST_LABELS[NUM_TEST_SAMPLES] = {\n")
        f.write("  " + ", ".join(map(str, labels)) + "\n")
        f.write("};\n\n")
        f.write("#endif // MCU_TEST_VECTORS_H_\n")
        
    print(f"Generated {len(samples)} INT8 test vectors -> {DST_HEADER}")

if __name__ == "__main__":
    generate_test_vectors()
